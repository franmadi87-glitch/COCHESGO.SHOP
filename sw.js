const CACHE_NAME = 'coches-go-v1';
const APP_SHELL = [
  '/',
  '/index.html',
  '/manifest.json',
  '/icons/icon-192.png',
  '/icons/icon-512.png'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

// Estrategia: red primero, caché como respaldo si no hay conexión.
// Así los anuncios siempre se cargan actualizados cuando hay internet,
// y la app sigue abriendo (con el último contenido visto) sin conexión.
// IMPORTANTE: solo actuamos sobre peticiones a nuestra propia web.
// Las peticiones a Supabase (u otros dominios externos) se dejan pasar
// directamente, sin interceptarlas, para no bloquear ni ralentizar
// el inicio de sesión, la carga de anuncios, mensajes, etc.
self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET') return;
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
